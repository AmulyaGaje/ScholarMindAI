"""
ScholarMind AI – Professional PDF Report Generator (ReportLab)
==============================================================
Generates a beautifully styled academic-grade PDF report containing
the 21 structured analysis sections, cover page, and page numbers.
"""

import os
from io import BytesIO
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak, KeepTogether, ListFlowable, ListItem
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from reportlab.pdfgen import canvas

class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print total page count,
    running headers, and running footers on all pages except the cover page.
    """
    def __init__(self, *args, **kwargs):
        self.paper_id_str = kwargs.pop("paper_id_str", "ScholarMind AI")
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_elements(num_pages)
            super().showPage()
        super().save()

    def draw_page_elements(self, page_count):
        # Page 1 is the cover page - no headers/footers
        if self._pageNumber > 1:
            # Header
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(colors.HexColor("#4f46e5"))  # Indigo primary
            self.drawString(54, 745, "ScholarMind AI — Research Analysis Report")
            self.setFont("Helvetica", 8)
            self.setFillColor(colors.HexColor("#6b7280"))
            self.drawRightString(612 - 54, 745, f"Document ID: {self.paper_id_str[:8].upper()}")
            
            # Header line
            self.setStrokeColor(colors.HexColor("#e5e7eb"))
            self.setLineWidth(0.5)
            self.line(54, 737, 612 - 54, 737)

            # Footer line
            self.line(54, 52, 612 - 54, 52)

            # Footer
            self.setFont("Helvetica", 8)
            self.setFillColor(colors.HexColor("#9ca3af"))
            self.drawString(54, 40, "Generated by ScholarMind AI | Academic Recommendation Platform")
            self.drawRightString(612 - 54, 40, f"Page {self._pageNumber} of {page_count}")


def generate_analysis_pdf(analysis, paper) -> BytesIO:
    """
    Compiles structured paper analysis model into a professional PDF document.
    """
    buffer = BytesIO()
    
    # Page dimensions: letter is 612 x 792 pt. Margins: 54pt (0.75 in)
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=72,
        bottomMargin=72
    )

    styles = getSampleStyleSheet()
    
    # Custom color palette
    primary_color = colors.HexColor("#1e1b4b")  # Dark Navy
    accent_indigo = colors.HexColor("#4f46e5")  # Indigo Accent
    text_color = colors.HexColor("#1f2937")      # Charcoal Body Text
    muted_color = colors.HexColor("#4b5563")     # Slate Gray Secondary
    light_bg = colors.HexColor("#f9fafb")        # Soft Light Background

    # Custom Typography Styles
    title_style = ParagraphStyle(
        'CoverTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=24,
        leading=30,
        textColor=primary_color,
        spaceAfter=15,
        alignment=1 # Centered
    )

    subtitle_style = ParagraphStyle(
        'CoverSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=12,
        leading=16,
        textColor=accent_indigo,
        spaceAfter=40,
        alignment=1
    )

    metadata_style = ParagraphStyle(
        'CoverMetadata',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=muted_color,
        alignment=1
    )

    h1_style = ParagraphStyle(
        'SectionH1',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=primary_color,
        spaceBefore=18,
        spaceAfter=8,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        'ReportBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=15,
        textColor=text_color,
        spaceAfter=10
    )

    bullet_style = ParagraphStyle(
        'ReportBullet',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=text_color,
        leftIndent=15,
        firstLineIndent=-10,
        spaceAfter=6
    )

    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=8,
        leading=11,
        textColor=muted_color,
        spaceBefore=25,
        spaceAfter=10
    )

    story = []

    # ─── COVER PAGE ────────────────────────────────────────────────────────
    story.append(Spacer(1, 100))
    story.append(Paragraph("ScholarMind AI", subtitle_style))
    story.append(Paragraph("RESEARCH PAPER ANALYSIS REPORT", title_style))
    story.append(Spacer(1, 30))
    
    # Paper title
    paper_title = paper.title or "Untitled Research Paper"
    paper_title_style = ParagraphStyle(
        'CoverPaperTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=16,
        leading=22,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=15,
        alignment=1
    )
    story.append(Paragraph(paper_title, paper_title_style))

    # Authors
    authors_list = paper.authors
    authors_str = ", ".join(authors_list) if isinstance(authors_list, list) else (authors_list or "Not specified")
    story.append(Paragraph(f"<b>Authors:</b> {authors_str}", metadata_style))
    
    # Journal & Year
    journal_str = paper.journal or "Academic Repository"
    year_str = str(paper.year) if paper.year else "N/A"
    story.append(Paragraph(f"<b>Venue:</b> {journal_str} | <b>Year:</b> {year_str}", metadata_style))
    
    story.append(Spacer(1, 120))
    analysis_date = datetime.now().strftime("%B %d, %Y")
    story.append(Paragraph(f"<b>Generated on:</b> {analysis_date}", metadata_style))
    story.append(Paragraph("Generated by ScholarMind AI Platform", metadata_style))
    story.append(PageBreak())

    # ─── SECTION BUILDER HELPER ───────────────────────────────────────────
    def add_section(title_text, content):
        if not content:
            content = "Not explicitly stated in the paper."
        story.append(Paragraph(title_text, h1_style))
        if isinstance(content, list):
            for idx, item in enumerate(content):
                story.append(Paragraph(f"• &nbsp; {item}", bullet_style))
        else:
            story.append(Paragraph(content, body_style))
        story.append(Spacer(1, 6))

    # ─── MAIN REPORT SECTIONS ──────────────────────────────────────────────
    add_section("Executive Summary", analysis.executive_summary)
    add_section("1. Paper Overview", analysis.paper_overview)
    add_section("2. Research Problem", analysis.research_problem)
    add_section("3. Research Objectives", analysis.objectives)
    add_section("4. Background and Context", analysis.background)
    add_section("5. Related Work / Literature", analysis.related_work)
    add_section("6. Proposed Approach", analysis.proposed_approach)
    add_section("7. Methodology", analysis.methodology)
    add_section("8. System / Model Architecture", analysis.architecture)
    add_section("9. Experimental Setup", analysis.experimental_setup)
    add_section("10. Results and Findings", analysis.results)
    add_section("11. Key Findings", analysis.key_findings)
    add_section("12. Simple Understanding", analysis.simple_understanding)
    add_section("13. Technical Understanding", analysis.technical_understanding)
    add_section("14. Strengths of the Approach", analysis.strengths)
    add_section("15. Limitations", analysis.limitations)
    add_section("16. Future Scope", analysis.future_scope)
    add_section("17. Research Contribution", analysis.research_contribution)
    add_section("18. Practical Applications", analysis.practical_applications)
    add_section("19. Important Terminology", analysis.terminology)
    add_section("20. Final Understanding", analysis.final_understanding)
    
    # 21. Source-Based Disclaimer
    story.append(Spacer(1, 15))
    story.append(Paragraph("<b>Source-Based Disclaimer</b>", h1_style))
    story.append(Paragraph(
        "This report was generated from the contents of the uploaded research paper. "
        "Statements not explicitly supported by the source paper should not be treated as factual claims.", 
        disclaimer_style
    ))

    # Build document
    canvas_maker_lambda = lambda *args, **kwargs: NumberedCanvas(*args, paper_id_str=str(paper.id), **kwargs)
    doc.build(story, canvasmaker=canvas_maker_lambda)
    
    buffer.seek(0)
    return buffer
